"""The check of a pull request's text (scripts/checks/pr_text.py): the real list of what it refuses, how a rule is added, where a
hit is reported and how the script ends. No Docker, no network: it reads the text it is given."""
from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
from pathlib import Path

import pytest

CHECKS = Path(__file__).resolve().parents[1] / "scripts" / "checks"
spec = importlib.util.spec_from_file_location("pr_text", CHECKS / "pr_text.py")
P = importlib.util.module_from_spec(spec)
spec.loader.exec_module(P)

def real_rules():
    return P.load_rules((CHECKS / "pr_text_deny.txt").read_text())


def hits(text: str, where: str = "the body", rules=None):
    return P.scan([(where, text)], rules or real_rules())


@pytest.mark.parametrize("line", [
    "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>",
    "co-authored-by: ChatGPT <bot@example.com>",
    "  CO-AUTHORED-BY : someone",
    "Assisted-by: Copilot",
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated by ChatGPT",
    "- generated with Cursor",
    "  GENERATED USING Gemini",
    "**Generated with** an assistant",
])
def test_a_footer_or_trailer_of_an_attribution_is_refused(line):
    assert len(hits(f"What changed.\n\n{line}\n")) == 1


@pytest.mark.parametrize("line", [
    "The report is generated with round.py and read by the author.",
    "A rule says no `Co-Authored-By` trailer goes in a commit.",
    "refactor(go): files generated by a tool are skipped",
    "Skips the files generated by tree-sitter.",
    "Co-authored work is welcome; the trailer is not.",
    "Do not write Co-Authored-By: anything in a commit.",
    "A footer reads Assisted-by: a tool, and is refused at the start of a line.",
    "",
])
def test_a_sentence_that_only_names_the_rule_or_says_generated_inside_a_line_is_not_refused(line):
    assert hits(line) == []


def test_a_hit_names_the_text_the_line_the_rule_and_the_line_itself():
    found = P.scan([("the title", "fix: a thing"), ("the body", "A\nB\nGenerated with X\nD"),
                    ("commit abc1234", "feat: x\n\nCo-Authored-By: Y")], real_rules())
    assert [(h.where, h.line, h.rule.id, h.text) for h in found] == [
        ("the body", 3, "generated-footer", "Generated with X"),
        ("commit abc1234", 3, "attribution-trailer", "Co-Authored-By: Y"),
    ]


def test_a_rule_is_a_line_of_the_list_and_a_new_one_refuses_what_it_describes(tmp_path):
    extra = "wip :: ^(?:wip|do not merge)\\b :: not ready\n"
    rules = P.load_rules((CHECKS / "pr_text_deny.txt").read_text() + extra)
    assert [h.rule.id for h in hits("Do Not Merge yet", rules=rules)] == ["wip"]
    assert [h.rule.id for h in hits("WIP: more", rules=rules)] == ["wip"]
    assert hits("Wipe the cache", rules=rules) == []


def test_a_regex_may_have_alternation_and_flags_of_its_own():
    rules = P.load_rules("two :: ^(?:alpha|beta)$ :: a word\ncase :: (?-i:^Exact$) :: a case\n")
    assert [h.rule.id for h in hits("ALPHA", rules=rules)] == ["two"]
    assert [h.rule.id for h in hits("Exact", rules=rules)] == ["case"]
    assert hits("exact", rules=rules) == []


def test_the_reason_of_a_rule_may_hold_the_separator():
    [rule] = P.load_rules("one :: a :: why :: because\n")
    assert (rule.id, rule.regex.pattern, rule.reason) == ("one", "a", "why :: because")


def test_comments_and_blank_lines_of_the_list_are_not_rules():
    assert [r.id for r in P.load_rules("# a comment\n\n   \n  # another\nonly :: x :: why\n")] == ["only"]


@pytest.mark.parametrize("text, message", [
    ("just-an-id\n", "line 1: expected"),
    ("id :: regex\n", "line 1: expected"),
    ("id ::  :: reason\n", "line 1: expected"),
    ("# c\nok :: a :: why\nok :: b :: why\n", "line 3: the id 'ok' is already a rule"),
    ("bad :: ( :: why\n", "line 1: the regex of 'bad' is wrong"),
])
def test_a_rule_that_is_wrong_is_refused_with_its_line(text, message):
    with pytest.raises(ValueError, match=message):
        P.load_rules(text)


def test_commits_come_from_a_list_of_commits_or_a_list_of_pages_of_them():
    one = {"sha": "0123456789abcdef", "commit": {"message": "feat: one"}}
    two = {"sha": "fedcba9876543210", "commit": {"message": "feat: two\n\nbody"}}
    assert P.commit_texts([one, two]) == [("commit 0123456", "feat: one"), ("commit fedcba9", "feat: two\n\nbody")]
    assert P.commit_texts([[one], [two]]) == P.commit_texts([one, two])


def run(tmp_path, *, title="fix: a thing", body="Why.", commits=None, rules=None):
    files = {"--title-file": title, "--body-file": body}
    argv = []
    for flag, text in files.items():
        f = tmp_path / flag.strip("-")
        f.write_text(text)
        argv += [flag, str(f)]
    if commits is not None:
        f = tmp_path / "commits.json"
        f.write_text(json.dumps(commits))
        argv += ["--commits-json", str(f)]
    if rules is not None:
        f = tmp_path / "rules.txt"
        f.write_text(rules)
        argv += ["--rules", str(f)]
    return argv


def test_a_clean_pull_request_ends_in_zero(tmp_path, capsys):
    commit = {"sha": "a" * 40, "commit": {"message": "docs: a line"}}
    assert P.main(run(tmp_path, commits=[[commit]])) == 0
    assert "1 commit message(s)" in capsys.readouterr().out


@pytest.mark.parametrize("field, where", [("title", "the title, line 1"), ("body", "the body, line 2")])
def test_a_hit_in_the_title_or_the_body_ends_in_one_and_says_where(tmp_path, capsys, field, where):
    text = {"title": {"title": "Generated with Y"}, "body": {"body": "Why.\nCo-Authored-By: Z"}}[field]
    assert P.main(run(tmp_path, **text)) == 1
    out = capsys.readouterr().out
    assert where in out and "1 line(s)" in out


def test_a_hit_in_a_commit_ends_in_one_and_names_the_commit(tmp_path, capsys):
    commit = {"sha": "b" * 40, "commit": {"message": "feat: x\n\nCo-Authored-By: Z"}}
    assert P.main(run(tmp_path, commits=[commit])) == 1
    assert "commit bbbbbbb, line 3" in capsys.readouterr().out


def test_a_list_that_is_wrong_ends_in_two_without_reading_the_text(tmp_path, capsys):
    assert P.main(run(tmp_path, rules="broken\n")) == 2
    assert "line 1: expected" in capsys.readouterr().err


def test_the_text_of_a_hit_cannot_break_the_markdown_of_the_report():
    out = P.report(P.scan([("the body", "Generated with `x` y")], real_rules()), 0)
    assert "`Generated with 'x' y`" in out


@pytest.mark.skipif(shutil.which("git") is None, reason="git is not installed")
def test_the_commits_may_be_read_from_git(tmp_path, monkeypatch):
    def git(*args):
        subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", *args],
                       check=True, capture_output=True, cwd=tmp_path)
    git("init", "-q", "-b", "main")
    git("commit", "-q", "--allow-empty", "-m", "base")
    git("commit", "-q", "--allow-empty", "-m", "feat: one", "-m", "Co-Authored-By: Z")
    git("commit", "-q", "--allow-empty", "-m", "feat: two")
    monkeypatch.chdir(tmp_path)
    texts = P.git_texts("HEAD~2", "HEAD")
    assert [t[1].strip() for t in texts] == ["feat: two", "feat: one\n\nCo-Authored-By: Z"]
    assert all(t[0].startswith("commit ") for t in texts)


@pytest.mark.skipif(shutil.which("git") is None, reason="git is not installed")
def test_the_commits_of_a_range_of_git_are_checked_by_the_script(tmp_path, monkeypatch, capsys):
    def git(*args):
        subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", *args],
                       check=True, capture_output=True, cwd=tmp_path)
    git("init", "-q", "-b", "main")
    git("commit", "-q", "--allow-empty", "-m", "base")
    git("commit", "-q", "--allow-empty", "-m", "feat: one", "-m", "Co-Authored-By: Z")
    monkeypatch.chdir(tmp_path)
    assert P.main(["--base", "HEAD~1", "--head", "HEAD"]) == 1
    assert "line 3" in capsys.readouterr().out
    assert P.main(["--base", "HEAD", "--head", "HEAD"]) == 0
