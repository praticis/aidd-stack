GO_VERB_ALIASES = {"Del": "DELETE"}                                                       # prometheus/common/route
# net/http, gorilla, chi, gin, echo, fiber. Exported only: an unexported method is the package's own, never a framework's
# (`c.get("/api/projects", nil, out)` on an API client of the app)
GO_REGISTRARS = {"HandleFunc", "Handle", "Any", "Match", "All"} | {v for v in VERB_BY_NAME if v[0].isupper()} | set(GO_VERB_ALIASES)
GO_MOUNTS = {"Group", "PathPrefix", "Route", "Mount", "Subrouter", "WithPrefix"}         # prefix carriers
# a call that returns its receiver under a prefix: `WithPrefix` is prometheus/common/route's
GO_PREFIXED = {"Group", "WithPrefix"}
GO_APPS = re.compile(r"^(gin\.(Default|New)|echo\.New|fiber\.New|http\.NewServeMux)$")       # always the application
GO_ROUTERS = re.compile(r"^(chi\.(NewRouter|NewMux)|mux\.NewRouter)$")                     # the application when main builds it
GO_CHAIN_BUILDERS = {"Combo"}                                                             # m.Combo("/x").Get(h).Put(h)
GO_CHAIN_VERBS = {v: VERB_BY_NAME[v] for v in ("Get", "Post", "Put", "Patch", "Delete", "Head", "Options")}
GORILLA_LINKS = {"Methods", "Path", "PathPrefix", "Name", "Queries", "Headers", "HeadersRegexp", "Schemes", "Host",
                 "NewRoute"}                                                              # r.Methods("GET").Path("/x").Handler(h)
GO_SERVE = {"http.ListenAndServe": 1, "http.Serve": 1, "http.ListenAndServeTLS": 3, "http.ServeTLS": 1}   # handler's position
GO_KIT_HTTP = "github.com/go-kit/kit/transport/http"                                     # httptransport.NewClient(method, url, enc, dec)


class GoScanner(GoPaths, BaseScanner):
    relative_on_groups = True
    mount_scope = "go"
    scope_declarations = frozenset({"short_var_declaration", "var_spec", "const_spec", "range_clause"})   # not `=`
    defer_global_group_prefix = True

    def run(self) -> None:
        self.servemux_vars: set[str] = set()     # net/http ServeMux: a pattern ending in "/" is a whole subtree
        self.served: list[str] = []              # another file's router a server of this one serves (global id)
        self.openapi_client = b"Code generated by OpenAPI Generator" in self.src[:2048]
        self.swagger = b"Code generated by go-swagger" in self.src[:1024]
        self.echo = any(spec.startswith("github.com/labstack/echo") for spec, _ in self.imports.values())
        if self.swagger:
            self._swagger_base()
        self._functions: dict[str, Node] | None = None
        self._idents: dict[int, dict[str, list[Node]]] = {}
        for n in walk(self.fx.tree.root_node):
            if n.type in ("short_var_declaration", "assignment_statement", "var_spec"):
                self._maybe_group(n)
                if self.swagger and n.type == "assignment_statement":
                    self._swagger_route(n)
            elif n.type == "call_expression":
                self._call(n)
            elif n.type in ("function_declaration", "method_declaration"):
                self._encoder(n)
            elif n.type == "composite_literal":
                self._swagger_operation(n)

    def _maybe_group(self, n: Node) -> None:
        left = n.child_by_field_name("left") or n.child_by_field_name("name")
        right = n.child_by_field_name("right") or n.child_by_field_name("value")
        typ = n.child_by_field_name("type") if n.type == "var_spec" else None
        if right is None and typ is not None and ROUTER_TYPE.search(text(typ, self.src)) and not in_function(n):
            for c in (c for c in n.children if c.type == "identifier"):   # `var APIv1 *gin.RouterGroup`, that
                self.router_vars.add(text(c, self.src))                    # another file of the package assigns
            return
        if left is None or right is None:
            return
        if left.type == "expression_list" and left.named_child_count == 1:
            left = left.named_children[0]
        if left.type == "selector_expression":         # api.BaseRoutes.Users = api.BaseRoutes.APIRoot.PathPrefix("/users").Subrouter()
            value = right.named_children[0] if right.type == "expression_list" and right.named_child_count == 1 else right
            child = self._field_router(text(left, self.src))
            sub = self._router_expr(value) if value.type == "call_expression" else None
            if child is not None and sub is not None:
                self.mount(child, n, sub[0], n, sub[1])
            return
        rights = [c for c in right.children if c.is_named] if right.type == "expression_list" else [right]
        names = [text(c, self.src) for c in (left.children if left.type == "expression_list" else [left]) if c.type == "identifier"]
        for r in rights:
            if r.type != "call_expression":
                continue
            fn = r.child_by_field_name("function")
            while fn is not None and fn.type == "selector_expression" and text(fn.child_by_field_name("field"), self.src) in ("Use", "With") \
                    and fn.child_by_field_name("operand").type == "call_expression":
                r = fn.child_by_field_name("operand")           # r := app.Group("/todo").Use(auth): the group
                fn = r.child_by_field_name("function")
            if fn is None:
                continue
            fname = text(fn, self.src)
            last = fname.split(".")[-1]
            args = r.child_by_field_name("arguments")
            arg_nodes = [c for c in args.children if c.is_named] if args else []
            if last in GO_MOUNTS:
                self._record_group(names, r, fname, arg_nodes)
            elif last in ("NewServeMux", "NewRouter", "New", "Default", "NewMux") and re.search(r"\b(http|mux|chi|gin|echo|fiber|httprouter)\b", fname):
                # gin/echo/fiber build the application; a chi/gorilla router is the application only when main
                # builds it — a helper that builds one returns it to be mounted somewhere else.
                is_app = bool(GO_APPS.match(fname)) or (bool(GO_ROUTERS.match(fname)) and self._in_main(n))
                for nm in names:
                    self.router_vars.add(nm)
                    if is_app:
                        self.mark_app(nm, n)
                    if fname == "http.NewServeMux":
                        self.servemux_vars.add(nm)

    def _call(self, n: Node) -> None:
        fn = n.child_by_field_name("function")
        args = n.child_by_field_name("arguments")
        if fn is None or args is None:
            return
        callee = self.callee_of(fn)
        name, recv, recv_last = split_callee(callee)
        arg_nodes = [c for c in args.children if c.is_named]
        if not arg_nodes:
            return
        self._router_arguments(n, fn, arg_nodes)
        if self.convention_call(n, name, recv_last, callee, arg_nodes):
            return
        if self._chained_route(n, arg_nodes) or self._gorilla_route(n, name, arg_nodes):
            return
        if callee in GO_SERVE and len(arg_nodes) > GO_SERVE[callee]:
            self._serve(arg_nodes[GO_SERVE[callee]])
            return
        if name == "prepareRequest" and self.openapi_client and len(arg_nodes) >= 3:     # (ctx, localVarPath, localVarHTTPMethod, ..)
            p = self.path_of(arg_nodes[1], lenient=True)
            if p is not None:
                self.add_call(n, self.method_from_args(arg_nodes[2:3]), p, "generated-client")
            return
        if name == "NewClient" and len(arg_nodes) >= 3 and (self.imports.get(recv) or ("",))[0] == GO_KIT_HTTP:
            self._kit_client(n, callee, arg_nodes)
            return
        operand = fn.child_by_field_name("operand") if fn.type == "selector_expression" else None
        base = self._middleware_base(operand) if operand is not None else None
        if base is not None:                                        # r.With(paginate).Get("/", h): a route on r
            recv_last = base
        chain = self._chain_prefix(operand) if operand is not None and base is None else None
        if chain is not None:                                       # g.Group("/user").Use(mw).POST("", h)
            recv_last = text(operand, self.src)
            self.group_prefix[self.group_key(recv_last, n)] = chain
            self.router_vars.add(recv_last)
        default_mux = recv == "http" and name in ("Handle", "HandleFunc")   # http.Handle("/x", h): the default ServeMux
        if name == "Mount" and len(arg_nodes) >= 2 and recv_last:        # chi: r.Mount("/admin", adminRouter())
            p = self.path_of(arg_nodes[0])
            parent = self.router_key(self._field_router(recv) or recv_last, n)
            prefix = (self.prefix_for(recv_last, n) or "").rstrip("/") + (p or "")
            if p is not None and self._mount_router(arg_nodes[1], parent, prefix):
                return

        # ---- exposed routes ---------------------------------------------------------------
        # a receiver this file built as a router/group is one, whatever its name (`api := r.Group("/api")`)
        if name in GO_REGISTRARS and len(arg_nodes) >= 2 and (recv_last in self.router_vars or default_mux or not CLIENT_RECEIVER.search(recv_last)):
            first = arg_nodes[0]
            raw_first = unquote(text(first, self.src)) if first.type in STRING_NODES else None
            lit = raw_first if raw_first and re.match(r"^[A-Z]+ /", raw_first) else self.route_path(first, recv_last, n)
            method = VERB_BY_NAME.get(name) or GO_VERB_ALIASES.get(name) or (None if name in ("HandleFunc", "Handle", "Match") else "ANY")
            if name == "Match" and len(arg_nodes) >= 3:                 # gin: r.Match([]string{...}, "/x", h)
                lit = self.route_path(arg_nodes[1], recv_last, n)
            joined = None
            if self.echo and raw_first and not raw_first.startswith("/") and lit == "/" + raw_first:
                pre = self.prefix_for(recv_last, n)         # echo joins `g.prefix + path` as written: u.GET("s") on
                if pre:                                     # "/user" is /users
                    lit, joined = pre + raw_first, ""
            # grpc-gateway / httprouter: mux.Handle("GET", pattern, h) — v2 writes `http.MethodGet`
            verb = self._method_value(first) if name == "Handle" and len(arg_nodes) >= 3 else None
            verb_first = verb is not None
            if verb_first:
                method, lit = verb, self.route_path(arg_nodes[1], recv_last, n)
            if name == "Handle" and (default_mux or recv_last in self.servemux_vars) and lit and len(lit) > 1 and lit.endswith("/"):
                return                                                  # mux.Handle("/booking/v1/", sub): a mount, not a route
            if lit and (lit.startswith("/") or re.match(r"^[A-Z]+ /", lit)):
                handler = arg_nodes[-1]
                if self.is_handler_like(handler) or recv_last in self.router_vars or name in ("HandleFunc", "Handle"):
                    framework = "net/http"
                    if name in ("GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS", "Any", "Match"):
                        framework = "gin/echo"
                    elif name in ("Get", "Post", "Put", "Patch", "Delete", "Head", "Options", "All") or name in GO_VERB_ALIASES:
                        framework = "chi/fiber"
                    if verb_first:
                        framework = "grpc-gateway" if b"protoc-gen-grpc-gateway" in self.src[:512] else "httprouter"
                    methods = [method or "ANY"]
                    verbs = self._match_verbs(arg_nodes[0]) if name == "Match" else None
                    if verbs:                                           # gin: r.Match([]string{..}, "/x", h)
                        methods = list(verbs)
                    elif method is None:
                        gm = self._gorilla_methods(n)
                        if gm:
                            methods, framework = gm, "gorilla"
                    router = self._field_router(recv) or recv_last
                    rpc = re.match(r"^pattern_([A-Za-z0-9]+)_([A-Za-z0-9]+)_\d+$", text(arg_nodes[1], self.src)) if verb_first else None
                    for m in methods:
                        for pattern in expand_alternatives(lit):
                            self.add_endpoint(n, m, pattern, framework, handler, router=router, prefix=joined,
                                              handler_name=f"{rpc.group(1)}.{rpc.group(2)}" if rpc else None)   # the gRPC method
                    return

        # ---- outbound calls ---------------------------------------------------------------
        if name in OUTBOUND:
            if name in GO_REGISTRARS and len(arg_nodes) >= 2 and self.is_handler_like(arg_nodes[-1]) and arg_nodes[-1].type not in STRING_NODES \
                    and any(self.path_of(a) is not None for a in arg_nodes[:-1]):
                return                                                  # unknown router: r.Get("/x", h), huma.Get(api, "/x", h)
            if name in GENERIC_OUTBOUND and not CLIENT_RECEIVER.search(recv_last) and not callee.startswith("http."):
                return
            method = OUTBOUND[name] or self.method_from_args(arg_nodes)
            lenient = bool(CLIENT_RECEIVER.search(recv_last)) or callee.startswith("http.")
            for a in arg_nodes:
                p = self.path_of(a, lenient=lenient)
                if p is not None:
                    self.add_call(n, method, p, callee)
                    return

    def _match_verbs(self, n: Node) -> tuple[str, ...] | None:
        """The verbs of gin's `Match`: a `[]string{..}` written there, or a variable holding one — of the function, of
        the package (another file: `MethodsPutPost`) or of an imported package (`api.MethodsPutPost`)."""
        if n.type == "composite_literal":
            return verb_list(n, self.src)
        if n.type == "identifier":
            bound, val = self.scopes.binding(n)
            if bound and val is not None and val.type == "composite_literal":
                return verb_list(val, self.src)
            return GoFacts.read(self.ctx).verb_lists.get(text(n, self.src))
        operand = n.child_by_field_name("operand") if n.type == "selector_expression" else None
        if operand is not None and text(operand, self.src) in self.imports and self.ctx.view is not None:
            target = self.resolve_import(self.imports[text(operand, self.src)][0])
            ctx = self.ctx.view.contexts.get(target) if target is not None else None
            if ctx is None:
                return None
            return GoFacts.read(ctx).verb_lists.get(text(n.child_by_field_name("field"), self.src))
        return None

    def _chained_route(self, n: Node, arg_nodes: list[Node]) -> bool:
        """`m.Combo("/x", mw).Get(h).Put(h)`: each verb a route on the Combo's path. True when `n` is one of
        those verbs, even with a path this file cannot read."""
        chained = self.route_chain(n, GO_CHAIN_BUILDERS, GO_CHAIN_VERBS)
        if chained is None:
            return False
        method, builder, recv = chained
        args = builder.child_by_field_name("arguments")
        first = args.named_children[0] if args is not None and args.named_child_count else None
        recv_text = self.callee_of(recv)
        recv_last = recv_text.split(".")[-1]
        if first is None or recv.type not in ("identifier", "selector_expression") \
                or (recv_last not in self.router_vars and CLIENT_RECEIVER.search(recv_last)):
            return True
        lit = self.route_path(first, recv_last, n)
        if lit is not None and lit.startswith("/"):
            self.add_endpoint(n, method, lit, "chi/fiber", arg_nodes[-1], router=self._field_router(recv_text) or recv_last)
        return True

    def _gorilla_route(self, n: Node, name: str, arg_nodes: list[Node]) -> bool:
        """gorilla's route builder, path and methods before or after the handler: `r.Methods("POST").Path("/x").Handler(h)`,
        `r.Path("/x").HandlerFunc(h).Methods("GET")`. A `PathPrefix` serves a whole tree: a route only with its
        methods (`MainRouter.PathPrefix("/.well-known/x").Handler(h).Methods("GET")`); without them, the mount of the
        router `http.StripPrefix` hands the rest of the path to. True when `n` (the `Handler` call) is one."""
        if name not in ("Handler", "HandlerFunc") or len(arg_nodes) != 1:
            return False
        cur, _ = member(n.child_by_field_name("function"))
        methods: list[str] = []
        path = prefix = None
        while cur is not None and cur.type == "call_expression":
            recv, link = member(cur.child_by_field_name("function"))
            verb = text(link, self.src) if link is not None else ""
            if verb not in GORILLA_LINKS:
                return False
            args = cur.child_by_field_name("arguments")
            args = args.named_children if args is not None else []
            if verb == "Methods":
                methods += [m for a in args if (m := self.method_from_args([a]))]
            elif verb == "Path" and args:
                path = args[0]
            elif verb == "PathPrefix" and args:
                prefix = args[0]
            cur = recv
        if cur is None or cur.type not in ("identifier", "selector_expression") or (path is None and prefix is None):
            return False
        recv_text = self.callee_of(cur)
        recv_last = recv_text.split(".")[-1]
        if recv_last not in self.router_vars and CLIENT_RECEIVER.search(recv_last):
            return False
        methods = list(dict.fromkeys(methods + (self._gorilla_methods(n) or [])))
        router = self._field_router(recv_text) or recv_last
        base = self.path_of(prefix) if prefix is not None else ""
        if base is None:
            return True
        if path is None and not methods:
            stripped = self._stripped(arg_nodes[0])
            if stripped is not None:
                under = (self.prefix_for(recv_last, n) or "").rstrip("/") + stripped[0]   # what the inner router no longer sees
                self._mount_router(stripped[1], self.router_key(router, n), under)
            return True
        lit = self.route_path(path, recv_last, n) if path is not None else base
        if lit is not None and path is not None and base:
            lit = base.rstrip("/") + "/" + lit.lstrip("/")
        if lit is not None and lit.startswith("/"):
            for m in methods or ["ANY"]:
                for pattern in expand_alternatives(lit):
                    self.add_endpoint(n, m, pattern, "gorilla", arg_nodes[0], router=router)
        return True

    def _stripped(self, handler: Node) -> tuple[str, Node] | None:
        """`http.StripPrefix("/addsvc", h)` → ("/addsvc", h): `h` sees the path without the prefix."""
        h = unwrap_arg(handler)
        fn = h.child_by_field_name("function") if h.type == "call_expression" else None
        args = h.child_by_field_name("arguments") if fn is not None else None
        if fn is None or args is None or self.callee_of(fn) != "http.StripPrefix" or args.named_child_count != 2:
            return None
        p = self.path_of(args.named_children[0])
        return (p, args.named_children[1]) if p is not None else None

    def _mount_router(self, n: Node, parent: tuple[int, str], prefix: str) -> bool:
        """The router `n` names mounted on `parent` under `prefix`: a router of this file, or the one a function
        returns (`r.Mount("/api/v1", apiv1.Routes())`). False when `n` names neither."""
        child = self._router_of(n)
        if child is not None:
            self.mounts.mount(child, parent, prefix)
            return True
        g = self._returned_router(n)
        if g is not None:
            self.foreign.append((g, parent, prefix))
            return True
        return False

    def _serve(self, handler: Node) -> None:
        """`http.Serve(l, h)` with `h` another file's router (`h := addtransport.NewHTTPHandler(...)`): that router
        is an application too, whatever else mounts it."""
        h = unwrap_arg(handler)
        if h.type == "identifier":
            h = self.resolve_local(h)
        g = self._returned_router(h) if h is not None else None
        if g is not None:
            self.served.append(g)

    def finish(self) -> None:
        super().finish()
        for g in dict.fromkeys(self.served):
            self.out.publish(g, MountEdge(APP, ""), self.mount_scope)

    def _kit_client(self, n: Node, callee: str, arg_nodes: list[Node]) -> None:
        """go-kit `httptransport.NewClient("GET", tgt, encodeX, decodeX)`: the method is the first argument, the path
        the URL's (`tgt.Path = "/paths"`) or, when the URL has none, what the encoder sets (`req.URL.Path = ...`, in
        any file of the package: `compose`)."""
        method = self.method_from_args(arg_nodes[:1])
        p = self.path_of(arg_nodes[1], lenient=True)
        if p and has_literal_segment(normalize_path(p)):
            self.add_call(n, method, p, callee)
            return
        enc = arg_nodes[2]                                          # tgt.Path = "": the encoder sets it
        unit = self._function_unit(enc) if enc.type in ("identifier", "selector_expression") else None
        item = self.call_info(n, method, "", callee) if unit is not None else None
        if item is not None:
            self.out.pending.append(Pending(item, EncodedCall(f"{unit[0]}:{unit[1]}")))

    def _swagger_operation(self, n: Node) -> None:
        """go-swagger's generated client: each operation is a `&runtime.ClientOperation{Method: "GET", PathPattern:
        "/alerts", ..}` (the spec's `basePath` is added by the transport at runtime, like a base URL)."""
        typ = n.child_by_field_name("type")
        if typ is None or text(typ, self.src) != "runtime.ClientOperation":
            return
        fields = dict(self._keyed_fields(n))
        method, pattern = fields.get("Method"), fields.get("PathPattern")
        p = self.path_of(pattern, lenient=True) if pattern is not None else None
        if p is not None:
            self.add_call(n, self.method_from_args([method]) if method is not None else None, p, "generated-client")

    def _swagger_route(self, n: Node) -> None:
        """go-swagger's generated server: `o.handlers["GET"]["/alerts"] = alert.NewGetAlerts(o.context, o.AlertGetAlertsHandler)`
        in `restapi/operations`. The path is relative to the spec's `basePath`, which `restapi/embedded_spec.go` holds:
        the route waits for it (`compose`)."""
        left = n.child_by_field_name("left")
        left = left.named_children[0] if left is not None and left.type == "expression_list" and left.named_child_count == 1 else left
        inner = left.child_by_field_name("operand") if left is not None and left.type == "index_expression" else None
        if inner is None or inner.type != "index_expression" or not text(inner.child_by_field_name("operand"), self.src).endswith(".handlers"):
            return
        verb, pattern = inner.child_by_field_name("index"), left.child_by_field_name("index")
        method = unquote(text(verb, self.src)).upper() if verb is not None and verb.type in STRING_NODES else None
        if method not in HTTP_METHODS or pattern is None or pattern.type not in STRING_NODES:
            return
        right = n.child_by_field_name("right")
        handler = re.search(r"\.(\w+)\)\s*$", text(right, self.src)) if right is not None else None
        ep = self.endpoint_info(n, method, unquote(text(pattern, self.src)), "go-swagger", handler.group(1) if handler else None)
        self.out.pending.append(Pending(ep, SwaggerRoute(dir_of(dir_of(self.fx.file.path)))))

    def _swagger_base(self) -> None:
        """go-swagger's `embedded_spec.go`: the spec as a JSON string, whose `basePath` its package's routes live under."""
        m = re.search(rb'"basePath":\s*"([^"]*)"', self.src)
        if m:
            self.out.publish(dir_of(self.fx.file.path), SwaggerBase(m.group(1).decode()))

    def _encoder(self, fn: Node) -> None:
        """A function that sets the path of the `*http.Request` it takes — go-kit's request encoder, `req.URL.Path =
        "/profiles/" + id` — publishes that path (`Encoder`) for the clients built with it."""
        params = fn.child_by_field_name("parameters")
        reqs = [text(c, self.src) for d in (params.named_children if params is not None else ())
                if (t := d.child_by_field_name("type")) is not None and text(t, self.src) == "*http.Request"
                for c in d.children if c.type == "identifier"]
        body = fn.child_by_field_name("body")
        if len(reqs) != 1 or body is None or f"{reqs[0]}.URL.Path" not in text(body, self.src):
            return
        last = None
        for d in walk(body):
            left = d.child_by_field_name("left") if d.type == "assignment_statement" else None
            if left is not None and text(left, self.src) == f"{reqs[0]}.URL.Path":
                last = d
        right = last.child_by_field_name("right") if last is not None else None
        if right is not None and right.type == "expression_list" and right.named_child_count == 1:
            right = right.named_children[0]
        op = last.child_by_field_name("operator") if last is not None else None
        p = None if right is None else self.path_of(last if op is not None and text(op, self.src) == "+=" else right, lenient=True)
        name = self._function_name(fn)
        if p is not None and name is not None:
            self.out.publish(f"{dir_of(self.fx.file.path)}:{name}", Encoder(p))

    @classmethod
    def compose(cls, out: HttpResult, repo: RepoInfo, view=None) -> None:
        """The mount graph (`BaseScanner.compose`), then the go-kit clients whose path their encoder sets: one encoder
        with one path, of the package the client names."""
        super().compose(out, repo, view)
        bases = out.facts_of(SwaggerBase)
        for p in out.waiting(SwaggerRoute):
            found = {b.base_path for b in bases.get(p.wait.spec_dir, ())}
            out.endpoints.append(rebased(repo, p.item, next(iter(found))) if len(found) == 1 else p.item)
        encoders = out.facts_of(Encoder)
        for p in out.waiting(EncodedCall):
            paths = {e.path for e in encoders.get(p.wait.encoder, ())}
            raw = next(iter(paths)) if len(paths) == 1 else None
            path = normalize_path(raw) if raw else ""
            if raw and has_literal_segment(path):
                out.calls.append(replace(p.item, path=path, raw_path=raw))

    def _middleware_base(self, n: Node) -> str | None:
        """`r.With(mw).Use(mw2)` — only middleware on a variable: that variable's name (None for any other receiver)."""
        if n.type != "call_expression":
            return None
        while n.type == "call_expression":
            fn = n.child_by_field_name("function")
            if fn is None or fn.type != "selector_expression" or text(fn.child_by_field_name("field"), self.src) not in ("Use", "With"):
                return None
            n = fn.child_by_field_name("operand")
        return text(n, self.src) if n.type == "identifier" else None

    def _chain_prefix(self, n: Node) -> str | None:
        """The prefix a receiver chain carries — `g.Group("/user").Use(mw)` → "/user" (plus g's own); None when the
        chain holds no group."""
        if n.type != "call_expression":
            return None
        fn = n.child_by_field_name("function")
        args = n.child_by_field_name("arguments")
        if fn is None or args is None or fn.type != "selector_expression":
            return None
        field, operand = fn.child_by_field_name("field"), fn.child_by_field_name("operand")
        if field is None or operand is None:
            return None
        verb = text(field, self.src)
        if verb in ("Use", "With"):                                     # middleware: same prefix
            return self._chain_prefix(operand)
        if verb not in GO_PREFIXED:
            return None
        arg_nodes = [c for c in args.children if c.is_named]
        p = self.group_path(arg_nodes[0]) if arg_nodes else None
        if p is None:
            return None
        inner = self._chain_prefix(operand)
        base = inner if inner is not None else (self.prefix_for(text(operand, self.src).split(".")[-1], n) or "")
        return base.rstrip("/") + p

    def region_of(self, call: Node, fn: Node) -> Region | None:
        """chi/fiber `r.Route("/x", func(r chi.Router) {...})`, chi `r.Group(func(r chi.Router) {...})` and
        `m.Group("/x", func() { m.Get(...) })` — the closure's routes live under the prefix."""
        callee = call.child_by_field_name("function")
        args = call.child_by_field_name("arguments")
        if callee is None or args is None or callee.type != "selector_expression":
            return None
        verb = text(callee.child_by_field_name("field"), self.src)
        if verb not in ("Route", "Group"):
            return None
        outer = text(callee.child_by_field_name("operand"), self.src).split(".")[-1]
        arg_nodes = [c for c in args.children if c.is_named]
        first = arg_nodes[0] if arg_nodes else None
        p = "" if first is fn else self.path_of(first) if first is not None else None
        if p is None:
            return None
        return Region(outer, p, same_router=verb == "Group")

    def closure_uses(self, fn: Node, receiver: str) -> list[tuple[Node, str]]:
        """`addRoutes := func() { m.Get(..) }`: given as the body of a group on `m` (`m.Group("/x", addRoutes)`), under
        the group's path; called inside a group (`addRoutes()`), under what `m` has there."""
        name = self._function_name(fn) if fn.type == "func_literal" else None
        scope = enclosing_function(fn) if name is not None else None
        if scope is None:
            return []
        later = (u for u in self._identifiers(scope).get(name, ()) if u.start_byte >= fn.end_byte)   # not the declaration
        return [use for use in (self._closure_use(u, receiver) for u in later) if use is not None]

    def _identifiers(self, scope: Node) -> dict[str, list[Node]]:
        """The identifiers of a function by name, indexed once per function."""
        if scope.id not in self._idents:
            idx: dict[str, list[Node]] = {}
            for d in walk(scope):
                if d.type == "identifier":
                    idx.setdefault(text(d, self.src), []).append(d)
            self._idents[scope.id] = idx
        return self._idents[scope.id]

    def _closure_use(self, u: Node, receiver: str) -> tuple[Node, str] | None:
        """`u`, a closure's name, as a use that registers its routes: the callee of a call, or an argument of a group
        on `receiver`."""
        parent = u.parent
        if parent is not None and parent.type == "call_expression":
            callee = parent.child_by_field_name("function")
            return (parent, "") if callee is not None and callee.id == u.id else None
        if parent is None or parent.type != "argument_list" or parent.parent is None:
            return None
        region = self.region_of(parent.parent, u)
        if region is not None and region.same_router and region.outer == receiver:
            return parent.parent, region.prefix
        return None

    def _router_of(self, n: Node) -> tuple[int, str] | None:
        """The router a Mount argument names: a variable, or the variable a function of this file returns."""
        if n.type == "identifier":
            return self.router_key(text(n, self.src), n)
        if n.type != "call_expression" or n.child_by_field_name("function") is None:
            return None
        if self._functions is None:
            self._functions = {text(d.child_by_field_name("name"), self.src): d for d in walk(self.fx.tree.root_node)
                               if d.type == "function_declaration"}
        d = self._functions.get(text(n.child_by_field_name("function"), self.src))
        for r in walk(d) if d is not None else ():
            if r.type == "return_statement":
                ids_ = [c for c in walk(r) if c.type == "identifier"]
                if len(ids_) == 1:
                    return self.router_key(text(ids_[0], self.src), ids_[0])
                return None
        return None

    # -- routers other files name: package variables, returned routers, router parameters, struct fields ---------
    def read_imports(self) -> dict[str, tuple[str, str | None]]:
        """`import apiv1 "example.com/routers/api/v1"` → apiv1; without a name, the path's last element (a `/v2` is
        skipped)."""
        out: dict[str, tuple[str, str | None]] = {}
        for decl in self.fx.tree.root_node.children:
            if decl.type != "import_declaration":
                continue
            for spec in (d for d in walk(decl) if d.type == "import_spec"):
                path, name = spec.child_by_field_name("path"), spec.child_by_field_name("name")
                if path is None:
                    continue
                imp = unquote(text(path, self.src))
                parts = imp.split("/")
                alias = text(name, self.src) if name is not None else \
                    (parts[-2] if len(parts) > 1 and re.fullmatch(r"v\d+", parts[-1]) else parts[-1]).split(".")[0].replace("-", "_")
                if alias not in ("_", "."):
                    out[alias] = (imp, None)
        return out

    def global_of(self, key: tuple[int, str]) -> str | None:
        scope, name = key
        unit = dir_of(self.fx.file.path)
        if scope == 0:
            if name.startswith("field:"):
                return f"field:{unit}:{name[6:]}"
            return f"var:{unit}:{name}" if re.fullmatch(r"[A-Za-z_]\w*", name) and name not in self.imports else None
        fn = self.function_of(scope)
        fname = self._function_name(fn) if fn is not None else None
        if fname is None:
            return None
        i = self._param(fn, name)[0]
        if i is not None:
            return f"param:{unit}:{fname}:{i}"
        return f"ret:{unit}:{fname}" if self.returns_name(fn, name) else None

    def router_param_type(self, fn: Node, name: str) -> str | None:
        decl = self._param(fn, name)[1]
        typ = decl.child_by_field_name("type") if decl is not None else None
        return text(typ, self.src) if typ is not None else None

    def _function_name(self, fn: Node) -> str | None:
        """`Routes`, or `todosResource.Routes` for a method: two types of a package may both have a `Routes`. A closure
        assigned to a variable is called by that name (`addActionsRoutes := func(m *web.Router, ...)`)."""
        if fn.type == "func_literal":
            decl = fn.parent.parent if fn.parent is not None and fn.parent.type == "expression_list" else fn.parent
            left = decl.child_by_field_name("left") if decl is not None and decl.type in ("short_var_declaration",
                                                                                          "assignment_statement") else None
            names = [c for c in left.named_children] if left is not None and left.type == "expression_list" else [left]
            return text(names[0], self.src) if len(names) == 1 and names[0] is not None and names[0].type == "identifier" else None
        if fn.type not in ("function_declaration", "method_declaration"):
            return None
        name = text(fn.child_by_field_name("name"), self.src)
        recv = fn.child_by_field_name("receiver") if fn.type == "method_declaration" else None
        typ = next((d.child_by_field_name("type") for d in recv.named_children), None) if recv is not None else None
        return f"{text(typ, self.src).lstrip('*').split('[')[0]}.{name}" if typ is not None else name

    def _param(self, fn: Node, name: str) -> tuple[int | None, Node | None]:
        """Position of the parameter `name` of `fn` (the receiver does not count), and its declaration."""
        params = fn.child_by_field_name("parameters")
        i = 0
        for decl in params.named_children if params is not None else ():
            names = [c for c in decl.children if c.type == "identifier"]
            for c in names or [None]:
                if c is not None and text(c, self.src) == name:
                    return i, decl
                i += 1
        return None, None

    def _field_router(self, recv: str) -> str | None:
        """`api.BaseRoutes.Users` → `field:BaseRoutes.Users`: a router kept in a struct field, which the package's
        files share whatever the variable is called. Not a package's variable (`http.DefaultServeMux`)."""
        parts = recv.split(".")
        if len(parts) < 2 or "(" in recv or parts[0] in self.imports:
            return None
        return "field:" + ".".join(parts[1:])

    def _router_expr(self, n: Node) -> tuple[str, str] | None:
        """A router expression as (router name, the prefix it adds to that router's own): `v1`,
        `api.BaseRoutes.APIRoot`, `v1.Group("/users")`, `r.PathPrefix("/x").Subrouter()`, with middleware (`Use`,
        `With`) in between."""
        if n.type == "identifier":
            return text(n, self.src), ""
        if n.type == "selector_expression":
            field = self._field_router(text(n, self.src))
            return (field, "") if field is not None else None
        fn = n.child_by_field_name("function") if n.type == "call_expression" else None
        if fn is None or fn.type != "selector_expression":
            return None
        verb, operand = text(fn.child_by_field_name("field"), self.src), fn.child_by_field_name("operand")
        if verb in ("Subrouter", "Use", "With"):
            return self._router_expr(operand)
        if verb not in GO_PREFIXED | {"PathPrefix"}:
            return None
        args = n.child_by_field_name("arguments")
        first = args.named_children[0] if args is not None and args.named_child_count else None
        p = self.group_path(first) if first is not None and first.type != "func_literal" else None
        base = self._router_expr(operand) if p is not None else None
        return (base[0], base[1].rstrip("/") + p) if base is not None else None

    def _function_unit(self, fn: Node) -> tuple[str, str] | None:
        """(package directory, name) of the function a call names: `F` of this package, `pkg.F` of an imported one,
        the method of a value built in place (`todosResource{}.Routes`), or of a value whose type the code declares
        (`api.v1.Register(..)`)."""
        if fn.type == "identifier":
            return dir_of(self.fx.file.path), text(fn, self.src)
        operand = fn.child_by_field_name("operand") if fn.type == "selector_expression" else None
        while operand is not None and operand.type in ("parenthesized_expression", "unary_expression"):
            operand = operand.named_children[-1] if operand.named_child_count else None
        if operand is not None and operand.type == "composite_literal" and operand.child_by_field_name("type") is not None:
            typ = text(operand.child_by_field_name("type"), self.src)
            if "." not in typ:
                return dir_of(self.fx.file.path), f"{typ}.{text(fn.child_by_field_name('field'), self.src)}"
            return None
        if operand is not None and not (operand.type == "identifier" and text(operand, self.src) in self.imports):
            typ = self._value_type(operand)
            return self._method_unit(typ, text(fn.child_by_field_name("field"), self.src)) if typ is not None else None
        if operand is None or operand.type != "identifier" or text(operand, self.src) not in self.imports:
            return None
        target = self.resolve_import(self.imports[text(operand, self.src)][0])
        return (target or ".", text(fn.child_by_field_name("field"), self.src)) if target is not None else None

    def _value_type(self, n: Node) -> str | None:
        """The type the code declares for a value: `x` a receiver or a parameter of a function around it
        (`func (api *API) Register(r *route.Router)`) or a local assigned a composite literal (`m := &pkg.T{}`); `x.f`
        a field of `x`'s struct. Any other local (`x := NewT()`) has no declared type: None."""
        if n.type == "selector_expression":
            return self._field_type(n)
        return self._local_type(n) if n.type == "identifier" else None

    def _field_type(self, n: Node) -> str | None:
        """`x.f`: the type of the field `f` of `x`'s struct, declared in any file of the package."""
        base = self._value_type(n.child_by_field_name("operand"))
        sname = base.lstrip("*") if base is not None else ""
        if not re.fullmatch(r"\w+", sname):        # a struct of another package, or a generic one: not read
            return None
        field = text(n.child_by_field_name("field"), self.src)
        return next((fields[field] for facts in self.ctx.file_facts.values()
                     if field in (fields := facts.get("structs", {}).get(sname, {}))), None)

    def _local_type(self, n: Node) -> str | None:
        """The identifier `n`: the nearest assignment before it, else a receiver or parameter, from the innermost
        function out."""
        name, scope = text(n, self.src), enclosing_function(n)
        while scope is not None:
            val = self.scopes.assigned_before(scope, n, name)
            if val is not None:
                return self._literal_type(val)
            decl = self._parameter(scope, name)
            if decl is not None:
                typ = decl.child_by_field_name("type")
                return text(typ, self.src) if typ is not None else None
            scope = enclosing_function(scope)
        return None

    def _literal_type(self, val: Node) -> str | None:
        """The type of a composite literal, also behind `&` or parentheses; None for any other value."""
        while val.type in ("expression_list", "unary_expression", "parenthesized_expression") and val.named_child_count == 1:
            val = val.named_children[0]
        typ = val.child_by_field_name("type") if val.type == "composite_literal" else None
        return text(typ, self.src) if typ is not None else None

    def _parameter(self, fn: Node, name: str) -> Node | None:
        """The receiver or parameter declaration of `fn` that declares `name`."""
        for field_name in ("receiver", "parameters"):
            params = fn.child_by_field_name(field_name)
            for decl in params.named_children if params is not None else ():
                if any(c.type == "identifier" and text(c, self.src) == name for c in decl.children):
                    return decl
        return None

    def _method_unit(self, typ: str, method: str) -> tuple[str, str] | None:
        """(package directory, `T.M`) of the method `M` of the declared type `typ`: `*Router` of this package,
        `*pkg.API` of an imported one."""
        pkg, _, tname = typ.lstrip("*").split("[")[0].rpartition(".")
        if not re.fullmatch(r"\w+", tname):
            return None
        if not pkg:
            return dir_of(self.fx.file.path), f"{tname}.{method}"
        target = self.resolve_import(self.imports[pkg][0]) if pkg in self.imports else None
        return (target, f"{tname}.{method}") if target is not None else None

    def _returned_router(self, n: Node) -> str | None:
        """`apiv1.Routes()`, `adminRouter()` from another file of the package: the router that function returns."""
        fn = n.child_by_field_name("function") if n.type == "call_expression" else None
        unit = self._function_unit(fn) if fn is not None else None
        return f"ret:{unit[0]}:{unit[1]}" if unit is not None else None

    def _router_arguments(self, n: Node, fn: Node, arg_nodes: list[Node]) -> None:
        """`users.UsersRegister(v1.Group("/users"))`, `addActionsRoutes(m, ...)`: a router handed to a function's
        parameter, with the prefix it has here (kept by `finish` only when the argument is a router of this file)."""
        unit = self._function_unit(fn)
        if unit is None:
            return
        for i, a in enumerate(arg_nodes):
            r = self._router_expr(a) if a.type in ("identifier", "call_expression", "selector_expression") else None
            if r is not None:
                self.router_args.append((f"param:{unit[0]}:{unit[1]}:{i}", r[0], n, r[1]))

    def _in_main(self, n: Node) -> bool:
        p = n.parent
        while p is not None and p.type not in ("function_declaration", "method_declaration", "func_literal"):
            p = p.parent
        name = p.child_by_field_name("name") if p is not None and p.type == "function_declaration" else None
        return name is not None and text(name, self.src) == "main"

    def _gorilla_methods(self, call: Node) -> list[str] | None:
        """`r.HandleFunc("/x", h).Methods("GET", "HEAD")` — `call` is the operand of `.Methods(...)`."""
        p = call.parent
        if p is None or p.type != "selector_expression":
            return None
        fld = p.child_by_field_name("field")
        if fld is None or text(fld, self.src) != "Methods":
            return None
        outer = p.parent
        if outer is None or outer.type != "call_expression":
            return None
        args = outer.child_by_field_name("arguments")
        found = [m for c in (args.named_children if args is not None else ()) if (m := self.method_from_args([c]))]
        return list(dict.fromkeys(found)) or None

